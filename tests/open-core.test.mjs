import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createOpenEngine} from '../site/open-core.js';
const config=JSON.parse(fs.readFileSync(new URL('../data/initial.json',import.meta.url),'utf8'));
const engine=createOpenEngine(config);
test('public raffle keeps original protected history out of view and respects inventory',()=>{
 let s=engine.initial();
 assert.equal(s.names.length,15);
 assert.ok(!s.names.includes('石淑華'));
 const original=JSON.stringify(s);
 assert.ok(!original.includes('handReceipt'));
 assert.ok(!original.includes('bonusAmount'));
 s=engine.apply(s,'selectName',{name:s.names[0]});
 s=engine.apply(s,'selectZone',{zone:'ruby'});
 const first=engine.remaining(s,'ruby').reduce((t,p)=>t+p.count,0);
 s=engine.apply(s,'enqueue',{id:'abc123'});
 assert.equal(s.queue.length,1);
 s=engine.apply(s,'draw');
 assert.equal(s.records.length,1);
 assert.equal(s.records[0].id,'abc123');
 const after=engine.remaining(s,'ruby').reduce((t,p)=>t+p.count,0);
 assert.equal(after,first-1);
 assert.ok(!JSON.stringify(s).includes('product'));
 assert.ok(!JSON.stringify(s).includes('handReceipt'));
 assert.ok(!JSON.stringify(s).includes('bonusAmount'));
 s=engine.apply(s,'clearScreen');
 assert.equal(engine.remaining(s,'ruby').reduce((t,p)=>t+p.count,0),after);
 assert.equal(s.queue.length,0);
 assert.equal(s.records.length,1);
});
